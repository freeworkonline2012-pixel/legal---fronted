/** تطبيع عربى للبحث: بلا تشكيل، توحيد الهمزات والياء والتاء المربوطة. */
export function normalizeArabic(input: string): string {
  return input
    .replace(/[ً-ٰٟـ]/g, '')
    .replace(/[أإآٱ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/ؤ/g, 'و')
    .replace(/ئ/g, 'ي')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

export interface CatalogHit extends CatalogForm {
  categoryId: string;
  categoryLabel: string;
}

/** بحث بكل كلمات الاستعلام (AND) فى اسم الصيغة أو اسم تصنيفها؛ `isAvailable` يُخفى ما لا يدعمه الخادم. */
export function searchCatalog(query: string, isAvailable: (kind: CatalogKind) => boolean): CatalogHit[] {
  const words = normalizeArabic(query).split(' ').filter(Boolean);
  if (words.length === 0) return [];
  const out: CatalogHit[] = [];
  for (const cat of CATALOG) {
    const catText = normalizeArabic(cat.label);
    for (const form of cat.forms) {
      if (!isAvailable(form.kind)) continue;
      const hay = `${normalizeArabic(form.title)} ${catText}`;
      if (words.every((w) => hay.includes(w))) out.push({ ...form, categoryId: cat.id, categoryLabel: cat.label });
    }
  }
  return out;
}

export function catalogSize(): number {
  return CATALOG.reduce((n, c) => n + c.forms.length, 0);
}
