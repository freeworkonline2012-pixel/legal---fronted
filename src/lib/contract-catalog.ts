/**
 * فهرس أنواع العقود المتاحة للصياغة (مرجع التبويب: تصنيفات «موسوعة صيغ العقود» المنشورة على lawhub.info).
 *
 * المرجع هنا للتصنيف والأسماء والترتيب فقط — لا ننسخ أى نص من صيغ الموقع (محمية بحقوق النشر).
 * ما يُصاغ فعلاً:
 *  - `lease` / `nda` / `services`: قوالب ثابتة محكَّمة على الخادم.
 *  - `custom`: هيكل ثابت + بنود الموضوع يصوغها نموذج لغوى (تحت حراسة الخصوصية والمخرجات)،
 *    ويُملأ اسم الصيغة تلقائياً فى خانة «نوع العقد» (≤ 60 حرفاً — حد الخادم).
 *
 * مستبعد عمداً: عقود الزواج الرسمية/العرفية (وثائق أحوال شخصية تصدر بإجراء رسمى)، والوصية (ليست عقداً)،
 * وقرارات الجمعيات العمومية والمخالصات (ليست عقوداً).
 */

export type CatalogKind = 'lease' | 'nda' | 'services' | 'custom';

export interface CatalogForm {
  title: string;
  kind: CatalogKind;
}

export interface CatalogCategory {
  id: string;
  label: string;
  forms: CatalogForm[];
}

/** صيغ لها قالب ثابت على الخادم (باقى الصيغ تُصاغ بالنوع الهجين «عقد آخر»). */
const TEMPLATED: Record<string, CatalogKind> = {
  'عقد إيجار': 'lease',
  'اتفاقية عدم إفصاح وسرية المعلومات': 'nda',
  'عقد خدمات (برمجيات / استشارات / تطوير)': 'services',
};

function category(id: string, label: string, titles: string[]): CatalogCategory {
  return { id, label, forms: titles.map((title) => ({ title, kind: TEMPLATED[title] ?? 'custom' })) };
}

